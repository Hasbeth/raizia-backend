CREATE EXTENSION IF NOT EXISTS vector;
CREATE OR REPLACE FUNCTION f_fold(text) RETURNS text
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
  SELECT translate(lower($1), 'áàäâãåéèëêíìïîóòöôõúùüûñç', 'aaaaaaeeeeiiiiooooouuuunc')
$$;
CREATE TABLE IF NOT EXISTS categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id integer REFERENCES categories(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  name text NOT NULL, slug text NOT NULL UNIQUE,
  description text NOT NULL DEFAULT '', keywords text NOT NULL DEFAULT '', sort integer NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS documents (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL, entity text NOT NULL DEFAULT '', doc_type text NOT NULL DEFAULT 'Otro',
  doc_date text NOT NULL DEFAULT '', official_url text NOT NULL DEFAULT '', summary text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'revision' CHECK (status IN ('borrador','revision','aprobado')),
  file_name text NOT NULL DEFAULT '', file_path text NOT NULL DEFAULT '', mime text NOT NULL DEFAULT '',
  file_size bigint NOT NULL DEFAULT 0, source_kind text NOT NULL DEFAULT 'upload',
  content_hash text NOT NULL DEFAULT '', text_chars integer NOT NULL DEFAULT 0, review_note text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::text), updated_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  weight real NOT NULL DEFAULT 1, staging_loaded boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_documents_status ON documents(status);
CREATE INDEX IF NOT EXISTS idx_documents_hash ON documents(content_hash);
CREATE INDEX IF NOT EXISTS idx_documents_lexical ON documents
  USING gin (to_tsvector('simple', f_fold(title || ' ' || summary || ' ' || entity)));
CREATE TABLE IF NOT EXISTS document_categories (
  document_id integer NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  category_id integer NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  PRIMARY KEY(document_id, category_id)
);
CREATE TABLE IF NOT EXISTS chunks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id integer NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  ord integer NOT NULL, heading text NOT NULL DEFAULT '', section text NOT NULL DEFAULT '',
  content text, content_hash text NOT NULL, embedding halfvec(384), embedding_model text,
  UNIQUE(document_id, ord), CHECK ((embedding IS NULL) = (embedding_model IS NULL))
);
-- simple conserva el stem/prefijos/sinónimos de la aplicación sin una segunda raíz española.
-- Índice de expresión: no duplica tsvector en cada fila. Las masivas quedan fuera.
CREATE INDEX IF NOT EXISTS idx_chunks_lexical ON chunks USING gin
  (to_tsvector('simple', f_fold(heading || ' ' || content))) WHERE content IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_chunks_content_hash ON chunks(content_hash);
CREATE INDEX IF NOT EXISTS idx_chunks_pending ON chunks(id) WHERE embedding IS NULL;
-- Algunas compilaciones de pgvector para PGlite no incluyen HNSW/halfvec.
-- EXCEPTION usa una subtransacción: el resto del esquema sigue disponible.
DO $$ BEGIN
  CREATE INDEX IF NOT EXISTS idx_chunks_embedding_hnsw ON chunks
    USING hnsw (embedding halfvec_cosine_ops) WITH (m=12, ef_construction=48);
EXCEPTION WHEN feature_not_supported OR undefined_object OR undefined_function THEN NULL;
END $$;
-- Vector léxico almacenado aparte: no ensancha ni reescribe chunks/HNSW.
CREATE TABLE IF NOT EXISTS chunk_search (
  chunk_id integer PRIMARY KEY REFERENCES chunks(id) ON DELETE CASCADE,
  tsv tsvector NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_chunk_search_tsv ON chunk_search USING gin (tsv);
CREATE OR REPLACE FUNCTION sync_chunk_search() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_catalog AS $$
BEGIN
  IF NEW.content IS NULL THEN
    DELETE FROM chunk_search WHERE chunk_id = NEW.id;
  ELSE
    INSERT INTO chunk_search(chunk_id, tsv)
    VALUES (NEW.id, to_tsvector('simple', f_fold(NEW.heading || ' ' || NEW.content)))
    ON CONFLICT (chunk_id) DO UPDATE SET tsv = EXCLUDED.tsv;
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER trg_chunk_search
AFTER INSERT OR UPDATE OF heading, content ON chunks
FOR EACH ROW EXECUTE FUNCTION sync_chunk_search();
CREATE TABLE IF NOT EXISTS storage_objects (
  bucket text NOT NULL, path text NOT NULL, bytes bigint NOT NULL, content_hash text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(bucket,path)
);
CREATE TABLE IF NOT EXISTS maintenance_jobs (
  name text PRIMARY KEY, owner text NOT NULL, expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS rate_limits (
  bucket text NOT NULL, window_start timestamptz NOT NULL, count int NOT NULL,
  PRIMARY KEY(bucket, window_start)
);
